-- دور ۱۱ (۲۰۲۶-۱۱-۰۹): نیاز روزانهٔ بخش روی رکورد برنامه — ورودی مستقیم
-- سرپرستار در جدول برنامهٔ شیفت (سه ردیف «تعداد صبح/عصر/شب (نیاز بخش)» به
-- تفکیک روز). تا پیش از این، نیاز فقط سه‌تاییِ ثابت در تنظیمات بیمارستان بود
-- که نوشتنش هم فقط دست مدیر بیمارستان است؛ نیازِ ماهِ بخش باید کنار خود
-- برنامه بنشیند تا سرپرستار (ward_manager) بتواند بنویسدش — سیاست‌های
-- schedules از قبل نوشتن را برای نقش‌های بخش باز گذاشته‌اند.
-- وضعیت: اعمال شد ۲۰۲۶-۱۱-۰۹ با «اجرا کن» سعید؛ ستون jsonb ‏NOT NULL با
-- پیش‌فرض {} وریفای شد و رفت‌وبرگشت نوشتن/خواندن روی رکورد برنامه تست و پاک شد.
alter table public.schedules
  add column if not exists daily_requirements jsonb not null default '{}'::jsonb;

comment on column public.schedules.daily_requirements is
  'نیاز روزانهٔ بخش برای همان ماه: {morning:number[], evening:number[], night:number[]} به ترتیب روزهای ماه؛ ورودی سرپرستار در جدول برنامه.';
